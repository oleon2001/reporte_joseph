-- Anomalía 5 (GT, AS400 Central): DEVOLUCIONES SIN DETALLES.
-- Parámetro: ? = días hacia atrás (por defecto 30).
SELECT d.NUMTIENDADEVOLUCION AS Tienda,
       d.NUMCAJADEVOLUCION   AS Caja,
       d.NUMTRANSACCIONDEV   AS TR_EPA
FROM cr.DEVOLUCIONVENTA d
INNER JOIN ventas.TRDMOV t
  ON d.NUMTIENDADEVOLUCION = t.TDADMV
 AND d.NUMCAJADEVOLUCION = t.CAJDMV
 AND t.TRSDMV = d.NUMTRANSACCIONDEV
EXCEPTION JOIN VENTAS.DETVDEV m
  ON (d.NUMTIENDAVENTA = m.TIEVDDEV AND d.NUMCAJAVENTA = m.CAJADDEV
      AND d.NUMTRANSACCIONVTA = m.TRANDDEV AND m.ARTIDDEV = t.CODDMV
      AND m.TIEDDDEV = d.NUMTIENDADEVOLUCION)
WHERE d.TIPOTRANSACCION = 'D' AND d.FECHADEVOLUCION >= CURRENT_DATE - ? DAYS
GROUP BY d.NUMTIENDADEVOLUCION, d.NUMCAJADEVOLUCION, d.NUMTRANSACCIONDEV
